"""Fixed-origin Railway transport for the unchanged owner's eBay API client."""
import hashlib
import hmac
import json
import time
from urllib.parse import urlsplit,parse_qs,unquote
from urllib.request import Request,build_opener,HTTPRedirectHandler
from urllib.error import HTTPError,URLError

ENDPOINT='https://sfb-api-production-19a54943.up.railway.app/api/seeker/ebay/'
PATH='/api/seeker/ebay/'
DOMAIN=b'SFB-Seeker-eBay-relay-v1'

class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self,*args,**kwargs): return None

class RailwayEbayTransport:
    def __init__(self,worker_key):
        if not worker_key: raise ValueError('Worker credential missing')
        self.worker_key=worker_key
    def call(self,payload):
        from ebay_api import ApiStop
        from browser_driver import Held
        body=json.dumps(payload,separators=(',',':')).encode()
        stamp=str(int(time.time()))
        derived=hmac.new(self.worker_key.encode(),DOMAIN,hashlib.sha256).digest()
        sig=hmac.new(derived,stamp.encode()+b'\nPOST\n'+PATH.encode()+b'\n'+body,hashlib.sha256).hexdigest()
        req=Request(ENDPOINT,data=body,headers={'Content-Type':'application/json',
                    'X-SFB-Time':stamp,'X-SFB-Signature':sig},method='POST')
        try:
            with build_opener(NoRedirect).open(req,timeout=40) as response:
                raw=response.read(5_000_001)
            if len(raw)>5_000_000: raise ApiStop('Railway eBay response too large')
            value=json.loads(raw)
            if not isinstance(value,dict): raise ValueError()
            return value
        except HTTPError as exc:
            if exc.code==404: raise Held('eBay item unavailable (404)') from None
            raise ApiStop('Railway eBay relay HTTP '+str(exc.code)+'; no retry') from None
        except (URLError,TimeoutError,ValueError):
            raise ApiStop('Railway eBay relay unavailable; no retry') from None
    def __call__(self,url,headers,data=None):
        # OAuth headers generated by the unchanged client contain placeholders,
        # never actual eBay credentials. No caller URL is forwarded to Railway.
        from ebay_api import ApiStop
        p=urlsplit(url)
        if p.scheme!='https' or p.netloc!='api.ebay.com': raise ApiStop('Unexpected eBay operation')
        if p.path=='/identity/v1/oauth2/token':
            result=self.call({'operation':'authenticate'})
            if result.get('ready') is not True: raise ApiStop('Railway eBay authentication failed')
            return {'access_token':'railway-relay-not-an-ebay-token'}
        if p.path=='/buy/browse/v1/item_summary/search':
            args=parse_qs(p.query)
            if set(args)!={'q','limit','filter'} or args['limit']!=['50'] or args['filter']!=['buyingOptions:{FIXED_PRICE|AUCTION}'] or len(args['q'])!=1:
                raise ApiStop('Unexpected eBay search parameters')
            return self.call({'operation':'search','query':args['q'][0]})
        if p.path.startswith('/buy/browse/v1/item/') and not p.query:
            return self.call({'operation':'item','item_id':unquote(p.path.rsplit('/',1)[1])})
        raise ApiStop('Unexpected eBay operation')


def relay_options(environ):
    return {'ebay_client_id':'railway-relay', 'ebay_client_secret':'not-a-credential',
            'api_transport':RailwayEbayTransport(environ.get('SUPABASE_KEY',''))}
